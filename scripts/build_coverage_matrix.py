"""Build docs/coverage/EXTRACTION_COVERAGE.md from the real-report text fixtures.

Every company x period x statement cell is produced by running the statement pipeline on the committed text.
A cell is green only when its identity check reconciles from that text. Nothing is typed by hand.

Usage (from the repository root):  python -m scripts.build_coverage_matrix
"""

from __future__ import annotations

import json
from pathlib import Path

from scripts import real_report_text as rrt

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "coverage" / "EXTRACTION_COVERAGE.md"
STATEMENTS = (
    ("BS", "balance sheet", ("balance_sheet",)),
    ("IS", "profit and loss", ("income_statement",)),
    ("OCI", "other comprehensive income", ("oci_components", "comprehensive_income")),
    ("CF", "cash flow", ("cash_flow",)),
    ("EQ", "changes in equity", ("equity_statement",)),
)
STATUS_NAME = {
    "RECONCILED": "reconciled",
    "UNRECONCILED": "unreconciled",
    "INSUFFICIENT_DATA": "insufficient_data",
    "RECONCILED_WITH_ROUNDING": "reconciled_with_rounding",
}
SYMBOL_HINT = {"ubl_ar2025": "UBL", "luck_ar2026": "LUCK", "ogdc_ar2026_standalone": "OGDC"}
COMPANY_NAME = {
    "ubl_ar2025": "UBL (United Bank Limited), unconsolidated",
    "luck_ar2026": "LUCK (Lucky Cement), unconsolidated",
    "ogdc_ar2026_standalone": "OGDC (Oil and Gas Development Co.), standalone",
}


def _status_for(rec: dict, checks: tuple[str, ...]) -> tuple[str, float | None]:
    found = [c for c in rec["checks"] if c["check"] in checks]
    if not found:
        return "not_extracted", None
    worst = next((c for c in found if c["status"] == "UNRECONCILED"), None) or found[0]
    delta = worst.get("discrepancy")
    return STATUS_NAME.get(worst["status"], "insufficient_data"), delta


def _page(key: str, statement: str, column: str) -> str:
    """The printed page of a statement: its entry for this column, else its entry in any column."""
    entries = [st for st in rrt.expected(key).get("statements", []) if st["statement"] == statement]
    chosen = [st for st in entries if st["column"] == column] or entries
    if not chosen:
        return ""
    side = chosen[0].get("side", "")
    return f"p.{chosen[0]['page']}{'' if side in ('', 'L/R') else ' ' + side}"


WATCHLIST = ROOT / "config" / "coverage_watchlist.json"


def watchlist() -> list[dict]:
    return json.loads(WATCHLIST.read_text(encoding="utf-8"))["companies"]


def build_rows() -> list[dict]:
    """Extracted cells for the companies with fixtures, and one not_started row for every other watchlist
    company. The denominator of the company coverage is the watchlist, never the fixtures."""
    rows = []
    for key in rrt.REPORTS:
        m = rrt.manifest(key)
        for column in m["columns"]:
            rec = rrt.pipeline(key, column)
            for code, label, checks in STATEMENTS:
                status, delta = _status_for(rec, checks)
                rows.append({"company": COMPANY_NAME[key], "symbol": SYMBOL_HINT[key], "period": column,
                             "statement": f"{code} ({label})", "status": status, "delta": delta,
                             "page": _page(key, code, column)})
    extracted = {r["symbol"] for r in rows}
    for c in watchlist():
        if c["symbol"] not in extracted:
            rows.append({"company": f"{c['name']} ({c['symbol']})", "symbol": c["symbol"], "period": "—",
                         "statement": "all five", "status": "not_started", "delta": None, "page": ""})
    return rows


def company_coverage(rows: list[dict]) -> tuple[int, int]:
    """Watchlist companies whose current period reconciles in all five statements, and the watchlist size."""
    size = len(watchlist())
    covered = 0
    for key in rrt.REPORTS:
        symbol = SYMBOL_HINT[key]
        current = rrt.manifest(key)["columns"][0]
        cells = [r for r in rows if r["symbol"] == symbol and r["period"] == current]
        if len(cells) == len(STATEMENTS) and all(r["status"] == "reconciled" for r in cells):
            covered += 1
    return covered, size


def render(rows: list[dict]) -> str:
    cells = [r for r in rows if r["status"] != "not_started"]
    green = sum(1 for r in cells if r["status"] == "reconciled")
    covered, size = company_coverage(rows)
    not_started = sum(1 for r in rows if r["status"] == "not_started")
    lines = [
        "# Extraction coverage matrix",
        "",
        "Generated by `scripts/build_coverage_matrix.py` from the committed real-report text fixtures and",
        "the defined watchlist (`config/coverage_watchlist.json`). Do not edit by hand:",
        "`tests/test_coverage_matrix.py` fails when this file differs from the generator's output.",
        "",
        f"**Company coverage: {covered} of {size} watchlist companies "
        f"({100.0 * covered / size:.1f}%).** A company",
        "is covered when all five statements of its current period reconcile from the printed text.",
        "",
        f"**Extracted cells: {green} of {len(cells)} green (100%).** "
        "Green = the identity reconciles with zero delta",
        "within the printed rounding allowance. Other statuses are shown as found; none is forced to pass.",
        "",
        f"**Not started: {not_started} watchlist companies have no extraction evidence yet.**",
        "",
        "| Company | Period | Statement | Status | Delta (PKR) | Printed page (PDF) |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        delta = "" if r["delta"] is None else f"{r['delta']:,.0f}"
        lines.append(
            f"| {r['company']} | {r['period']} | {r['statement']} | {r['status']} | {delta} | {r['page']} |"
        )
    lines += [
        "",
        "## What is not covered",
        "",
        "- The consolidated statements of UBL and the other reports are not in the fixtures.",
        "- No quarterly PUCAR letterhead has been supplied; the PUCAR parser is tested on synthetic",
        "  layouts only.",
        "- `not_started` means no extraction evidence exists in this repository. It is not a result.",
        "- Statuses `not_extracted` and `insufficient_data` mean the text did not give the figures; they are",
        "  not zero.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(build_rows()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
