"""Build docs/coverage/EXTRACTION_COVERAGE.md from the real-report text fixtures.

Every company x period x statement cell is produced by running the statement pipeline on the committed text.
A cell is green only when its identity check reconciles from that text. Nothing is typed by hand.

Usage (from the repository root):  python -m scripts.build_coverage_matrix
"""

from __future__ import annotations

import json
from pathlib import Path

from scripts import real_report_text as rrt

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "coverage" / "EXTRACTION_COVERAGE.md"
STATEMENTS = (
    ("BS", "balance sheet", ("balance_sheet",)),
    ("IS", "profit and loss", ("income_statement",)),
    ("OCI", "other comprehensive income", ("oci_components", "comprehensive_income")),
    ("CF", "cash flow", ("cash_flow",)),
    ("EQ", "changes in equity", ("equity_statement",)),
)
STATUS_NAME = {
    "RECONCILED": "reconciled",
    "UNRECONCILED": "unreconciled",
    "INSUFFICIENT_DATA": "insufficient_data",
    "RECONCILED_WITH_ROUNDING": "reconciled_with_rounding",
}
COMPANY_NAME = {
    "ubl_ar2025": "UBL (United Bank Limited), unconsolidated",
    "luck_ar2026": "LUCK (Lucky Cement), unconsolidated",
    "ogdc_ar2026_standalone": "OGDC (Oil and Gas Development Co.), standalone",
}


def _status_for(rec: dict, checks: tuple[str, ...]) -> tuple[str, float | None]:
    found = [c for c in rec["checks"] if c["check"] in checks]
    if not found:
        return "not_extracted", None
    worst = next((c for c in found if c["status"] == "UNRECONCILED"), None) or found[0]
    delta = worst.get("discrepancy")
    return STATUS_NAME.get(worst["status"], "insufficient_data"), delta


def _page(key: str, statement: str, column: str) -> str:
    """The printed page of a statement: its entry for this column, else its entry in any column."""
    entries = [st for st in rrt.expected(key).get("statements", []) if st["statement"] == statement]
    chosen = [st for st in entries if st["column"] == column] or entries
    if not chosen:
        return ""
    side = chosen[0].get("side", "")
    return f"p.{chosen[0]['page']}{'' if side in ('', 'L/R') else ' ' + side}"


def build_rows() -> list[dict]:
    rows = []
    for key in rrt.REPORTS:
        m = rrt.manifest(key)
        for column in m["columns"]:
            rec = rrt.pipeline(key, column)
            for code, label, checks in STATEMENTS:
                status, delta = _status_for(rec, checks)
                rows.append(
                    {
                        "company": COMPANY_NAME[key],
                        "period": column,
                        "statement": f"{code} ({label})",
                        "status": status,
                        "delta": delta,
                        "page": _page(key, code, column),
                    }
                )
    return rows


def render(rows: list[dict]) -> str:
    green = sum(1 for r in rows if r["status"] == "reconciled")
    total = len(rows)
    pct = 100.0 * green / total
    companies = {r["company"] for r in rows}
    seed = json.loads((ROOT / "database" / "seed" / "companies.json").read_text(encoding="utf-8"))
    seeded = len(seed) if isinstance(seed, list) else len(seed.get("companies", seed))
    lines = [
        "# Extraction coverage matrix",
        "",
        "Generated by `scripts/build_coverage_matrix.py` from the committed real-report text fixtures.",
        "Do not edit by hand: `tests/test_coverage_matrix.py` fails when this file differs from the",
        "generator's output.",
        "",
        f"**Green cells: {green} of {total} ({pct:.1f}%).** Green = the statement's identity reconciles from",
        "the printed text (zero delta within the printed rounding allowance). Other statuses are shown as",
        "found;none is forced to pass.",
        "",
        f"**Company coverage: {len(companies)} of {seeded} seeded companies "
        f"({100.0 * len(companies) / seeded:.1f}%).**",
        "The seeded master (`database/seed/companies.json`) has 51 companies; the supplied PSX listing has",
        "567 rows. Only the three companies below have committed page fixtures.",
        "",
        "| Company | Period | Statement | Status | Delta (PKR) | Printed page (PDF) |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        delta = "" if r["delta"] is None else f"{r['delta']:,.0f}"
        lines.append(
            f"| {r['company']} | {r['period']} | {r['statement']} | {r['status']} | {delta} | {r['page']} |"
        )
    lines += [
        "",
        "## What is not covered",
        "",
        "- The consolidated statements of UBL and the other reports are not in the fixtures.",
        "- No quarterly PUCAR letterhead has been supplied; the PUCAR parser is tested on synthetic",
        "  layouts only.",
        "- Companies other than these three have no extraction evidence.",
        "- Statuses `not_extracted` and `insufficient_data` mean the text did not give the figures; they are",
        "  not zero.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(build_rows()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
